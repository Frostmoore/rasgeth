#!/usr/bin/env node
// Rebuilds the generated parts of the site from the repository:
//   - assets/img/: the logo and the README's screenshots (docs/screenshots), copied;
//   - assets/icons.svg: the drawn icons, taken from packages/web/src/icons.tsx (the same shapes
//     as RedGiant's page) plus a few platform logos from simple-icons (CC0), as one sprite;
//   - assets/mascot-motion.css and the mascots inside index.html (between `<!-- mascots:NAME -->`
//     markers), drawn by @redgiant/mascot (needs `pnpm build` once, for packages/mascot/dist).
// With `--tavola <file>` it also writes a self-contained copy of index.html (CSS, scripts, icons
// and images inlined, links to the other pages made absolute) to show around before uploading.
//
//   node site/tools/build.mjs
//   node site/tools/build.mjs --tavola /path/to/tavola/index.html
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(SITE, "..");
/** Where the site is published: the tavola's links to the other pages point here. */
const PUBLIC_URL = "https://smpdigital.it/redgiant/";

// ---------- Images ----------

const IMG = join(SITE, "assets", "img");
mkdirSync(join(IMG, "shots"), { recursive: true });
const shots = [
  "canvas",
  "keychain",
  "knowledge",
  "local-models",
  "magic-automation",
  "phone",
  "team",
  "tools",
];
for (const s of shots) {
  copyFileSync(join(ROOT, "docs", "screenshots", `${s}.png`), join(IMG, "shots", `${s}.png`));
}
const pub = join(ROOT, "packages", "web", "public");
copyFileSync(join(pub, "icon-192.png"), join(IMG, "logo.png"));
copyFileSync(join(pub, "favicon.png"), join(IMG, "favicon.png"));
copyFileSync(join(pub, "apple-touch-icon.png"), join(IMG, "apple-touch-icon.png"));

// ---------- Icons ----------

/** The page's drawn icons the site uses (names without the `Icon` prefix). */
const ICONS = [
  "ArrowRight",
  "Book",
  "Box",
  "Canvas",
  "Chat",
  "Check",
  "Clock",
  "Cloud",
  "Copy",
  "Cpu",
  "Disk",
  "Download",
  "External",
  "Globe",
  "Key",
  "Layers",
  "Lock",
  "Monitor",
  "Moon",
  "Nodes",
  "Phone",
  "Server",
  "Shield",
  "Spark",
  "Sun",
  "Terminal",
  "Tree",
  "Users",
  "Wand",
  "Wifi",
  "Zap",
];
const tsx = readFileSync(join(ROOT, "packages", "web", "src", "icons.tsx"), "utf8");
const symbols = [];
for (const name of ICONS) {
  const m = new RegExp(
    `export const Icon${name} = \\([^)]*\\) => \\(\\s*<Svg([^>]*)>([\\s\\S]*?)</Svg>\\s*\\);`,
  ).exec(tsx);
  if (!m) throw new Error(`icons.tsx: no plain Icon${name}`);
  const filled = /\bfill\b/.test(m[1] ?? "");
  const body = (m[2] ?? "").replace(/\s+/g, " ").trim();
  if (body.includes("{")) throw new Error(`icons.tsx: Icon${name} has expressions`);
  const paint = filled
    ? 'fill="currentColor" stroke="none"'
    : 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
  symbols.push(`<symbol id="i-${name.toLowerCase()}" viewBox="0 0 24 24" ${paint}>${body}</symbol>`);
}
// Windows has no logo in simple-icons (removed at Microsoft's request): four panes, drawn here.
symbols.push(
  '<symbol id="b-windows" viewBox="0 0 24 24" fill="currentColor"><path d="M3 5.2 10.4 4.2v7.1H3zM11.4 4.05 21 2.7v8.6h-9.6zM3 12.3h7.4v7.1L3 18.4zM11.4 12.3H21V21l-9.6-1.35z"/></symbol>',
);
const webRequire = createRequire(join(ROOT, "packages", "web", "package.json"));
const si = await import(pathToFileURL(webRequire.resolve("simple-icons")).href);
for (const [id, key] of [
  ["apple", "siApple"],
  ["linux", "siLinux"],
  ["android", "siAndroid"],
  ["raspberrypi", "siRaspberrypi"],
  ["proxmox", "siProxmox"],
  ["docker", "siDocker"],
  ["github", "siGithub"],
]) {
  const icon = si[key] ?? si.default?.[key];
  if (!icon) throw new Error(`simple-icons: no ${key}`);
  symbols.push(
    `<symbol id="b-${id}" viewBox="0 0 24 24" fill="currentColor"><path d="${icon.path}"/></symbol>`,
  );
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by site/tools/build.mjs: drawn icons from packages/web/src/icons.tsx (shapes in the style of Feather, MIT); logos from simple-icons (CC0). -->\n${symbols.join("\n")}\n</svg>\n`;
writeFileSync(join(SITE, "assets", "icons.svg"), sprite);

// ---------- Mascots ----------

const mascot = await import(
  pathToFileURL(join(ROOT, "packages", "mascot", "dist", "index.js")).href
);
writeFileSync(
  join(SITE, "assets", "mascot-motion.css"),
  `/* Generated by site/tools/build.mjs from @redgiant/mascot (mascotMotionCss). */\n${mascot.mascotMotionCss()}\n`,
);

const lang = (it, en) => `<span lang="it">${it}</span><span lang="en">${en}</span>`;
const draw = (spec, state, size, id) =>
  mascot.mascotSvg(spec, { state, size, idPrefix: `${id}-` });

const agentSpec = mascot.mascotSpec("site-agent-ada", "agent");
const MASCOTS = {
  hierarchy: [
    { spec: mascot.mascotSpec("site-demigod", "demigod"), state: "idle", it: ["Demi-God", "sulle chat"], en: ["Demi-God", "on the chats"] },
    { spec: mascot.mascotSpec("site-god", "god"), state: "active", it: ["God", "guida RedGiant"], en: ["God", "runs RedGiant"] },
    { spec: mascot.mascotSpec("site-orchestrator", "orchestrator"), state: "think", it: ["Orchestratore", "uno per progetto"], en: ["Orchestrator", "one per project"] },
    { spec: agentSpec, state: "work", it: ["Agenti", "ognuno nel suo worktree"], en: ["Agents", "each in its own worktree"] },
    { spec: mascot.mascotSpec("site-sub-1", "subagent", agentSpec), state: "work", it: ["Sotto-agenti", "di breve durata"], en: ["Sub-agents", "short-lived"] },
  ],
  team: [
    { spec: mascot.mascotSpec("site-god", "god"), state: "active", it: ["God", "ti risponde"], en: ["God", "answering you"] },
    { spec: mascot.mascotSpec("site-chat", "assistant"), state: "idle", it: ["Chat", "a riposo"], en: ["Chat", "resting"] },
    { spec: agentSpec, state: "work", it: ["Ada", "al lavoro"], en: ["Ada", "working"] },
    { spec: mascot.mascotSpec("site-agent-linus", "agent"), state: "think", it: ["Linus", "ci pensa"], en: ["Linus", "thinking"] },
    { spec: mascot.mascotSpec("site-agent-grace", "agent"), state: "wait", it: ["Grace", "aspetta il tuo sì"], en: ["Grace", "waiting for your yes"] },
    { spec: mascot.mascotSpec("site-inspector", "inspector"), state: "idle", it: ["Ispettore", "solo lettura"], en: ["Inspector", "read-only"] },
  ],
};

let html = readFileSync(join(SITE, "index.html"), "utf8");
for (const [name, list] of Object.entries(MASCOTS)) {
  const size = name === "team" ? 72 : 64;
  const items = list
    .map(
      (m, i) =>
        `<li class="masc-card"><span class="mascot" style="--j:${(i * 0.37).toFixed(2)}">${draw(m.spec, m.state, size, `${name}${i}`)}</span><strong>${lang(m.it[0], m.en[0])}</strong><small>${lang(m.it[1], m.en[1])}</small></li>`,
    )
    .join("\n");
  const re = new RegExp(`(<!-- mascots:${name} -->)[\\s\\S]*?(<!-- /mascots:${name} -->)`);
  if (!re.test(html)) throw new Error(`index.html: no <!-- mascots:${name} --> markers`);
  html = html.replace(re, `$1\n${items}\n$2`);
}
writeFileSync(join(SITE, "index.html"), html);

// ---------- The tavola ----------

const at = process.argv.indexOf("--tavola");
if (at > 0) {
  const out = process.argv[at + 1];
  if (!out) throw new Error("--tavola needs a file");
  const read = (p) => readFileSync(join(SITE, p), "utf8");
  const dataUri = (p) => {
    const type = p.endsWith(".png") ? "image/png" : "image/svg+xml";
    return `data:${type};base64,${readFileSync(join(SITE, p)).toString("base64")}`;
  };
  let page = html
    .replace(/<link rel="stylesheet" href="(assets\/[^"]+)" \/>/g, (_, p) => `<style>\n${read(p)}\n</style>`)
    .replace(/<script src="(assets\/[^"]+)"( defer)?><\/script>/g, (_, p) => `<script>\n${read(p)}\n</script>`)
    .replace(/(src|href)="(assets\/img\/[^"]+)"/g, (_, a, p) => `${a}="${dataUri(p)}"`)
    .replace(/href="assets\/icons\.svg#/g, 'href="#')
    .replace(/href="(download\.html[^"]*)"/g, (_, p) => `href="${PUBLIC_URL}${p}"`)
    .replace(/href="index\.html(#[^"]*)?"/g, (_, h) => `href="${h ?? "#"}"`);
  const inlineSprite = sprite
    .replace("<svg ", '<svg style="display:none" aria-hidden="true" ')
    .replace(/<!--[\s\S]*?-->\n/, "");
  page = page.replace(/<body([^>]*)>/, (b) => `${b}\n${inlineSprite}`);
  if (/(src|href)="assets\//.test(page)) throw new Error("tavola: a path to assets/ is left");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, page);
  console.log(`tavola: ${out} (${Math.round(page.length / 1024)} KB)`);
}
console.log("site: images, icons and mascots rebuilt");
