// Writes lib/l10n/tool_words.g.dart: the page's words for the tools (`tool_<id>`, `toolDo_<id>`,
// `toolGrp_<group>`, `toolWhy_<id>` in packages/web/src/i18n.ts, it and en), so the app names them the same.
//
//   node apps/companion/tool/tool_words.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fillProduct } from "./product.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../../packages/web/src/i18n.ts"), "utf8");
const itAt = src.indexOf("\nconst it:");
const parts = { en: src.slice(0, itAt), it: src.slice(itAt) };
const re = /^ {2}(tool(?:Do|Grp|Why)?_[A-Za-z0-9_]+):\s*\n?\s*"((?:[^"\\]|\\.)*)",?$/gm;
const out = { it: {}, en: {} };
for (const [lang, text] of Object.entries(parts))
  for (const m of text.matchAll(re)) out[lang][m[1]] = fillProduct(JSON.parse(`"${m[2]}"`));
const dart = (o) =>
  Object.entries(o)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `    '${k}': r${JSON.stringify(v)},`)
    .join("\n");
const file = join(here, "../lib/l10n/tool_words.g.dart");
writeFileSync(
  file,
  `// Generated by tool/tool_words.mjs from packages/web/src/i18n.ts: do not edit.
// The tools' names, what they do and their groups, as the page says them.
// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes, unnecessary_string_escapes
const toolWords = <String, Map<String, String>>{
  'it': {
${dart(out.it)}
  },
  'en': {
${dart(out.en)}
  },
};
`,
);
console.log(`${Object.keys(out.it).length} it, ${Object.keys(out.en).length} en -> ${file}`);
