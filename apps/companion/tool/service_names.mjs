// Writes lib/settings/agents/service_names.g.dart: the services' names of the page's catalog
// (MCP_CATALOG in packages/protocol/src/mcp-catalog.ts: id and name), so the app names them the same.
//
//   node apps/companion/tool/service_names.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../../packages/protocol/src/mcp-catalog.ts"), "utf8");
const at = src.indexOf("export const MCP_CATALOG");
const re = /\n {4}id: "([^"]+)",\n {4}name: "((?:[^"\\]|\\.)*)",/g;
const names = {};
for (const m of src.slice(at).matchAll(re)) names[m[1]] = JSON.parse(`"${m[2]}"`);
const lines = Object.entries(names)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  '${k}': r${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(
  join(here, "../lib/settings/agents/service_names.g.dart"),
  `// Generated by tool/service_names.mjs from packages/protocol/src/mcp-catalog.ts: do not edit.
// The services' names, as the page says them.
// ignore_for_file: prefer_single_quotes
const serviceNames = <String, String>{
${lines}
};
`,
);
