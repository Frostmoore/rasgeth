// Writes test/fixtures/wizard_vectors.json and lib/setup/wizard/wizard_presets.g.dart (G42.17): the setup wizard's rules from the page's own
// packages/web/src/wizard.ts, for the Dart port (lib/setup/wizard/wizard_logic.dart): the steps for
// every mode, role, local offer and password; which may be skipped; the step after each; the ready
// choices of the approvals and which one a set is; the ways of thinking in use.
//
//   pnpm build && node --experimental-transform-types --import ./apps/companion/tool/ts_loader.mjs \
//     apps/companion/tool/wizard_vectors.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const w = await import(join(here, "../../../packages/web/src/wizard.ts"));

const steps = [];
for (const mode of [undefined, "standard", "advanced"])
  for (const role of [undefined, "full", "node"])
    for (const local of [undefined, true, false])
      for (const password of [false, true])
        steps.push({
          mode: mode ?? null,
          role: role ?? null,
          local: local ?? null,
          password,
          steps: w.stepsFor(mode, { role, local, password }),
        });
const all = w.stepsFor("advanced", {});
const skip = [];
for (const k of [...all, "wzAccount"])
  for (const must of [false, true]) skip.push({ step: k, must, skippable: w.skippable(k, { mustSetPassword: must }) });
const after = [];
for (const list of [all, w.stepsFor("standard", {}), w.stepsFor(undefined, { role: "node" })])
  for (const k of list) after.push({ list, from: k, to: w.stepAfter(list, k) });
const presets = w.PRESETS;
const presetOf = [
  [...w.PRESETS.careful],
  [...w.PRESETS.balanced].reverse(),
  [...w.PRESETS.free],
  ["platform"],
  [],
].map((h) => ({ humanOnly: h, preset: w.presetOf(h) ?? null }));
const state = (o) => ({
  config: { subscriptions: o.subs ?? {}, engine: o.engine ?? undefined, server: o.server ?? undefined },
  secretsSet: { keys: o.keys ?? [] },
  locked: { anthropic: !!o.lockedAnthropic, server: !!o.lockedServer },
});
const ways = [
  {},
  { subs: { claude: true } },
  { subs: { claude: true, chatgpt: true }, keys: ["openai"] },
  { lockedAnthropic: true },
  { engine: { variant: "docker", model: "x" } },
  { server: { baseUrl: "http://x" } },
  { lockedServer: true, keys: ["groq"] },
].map((o) => ({ input: o, ways: w.waysInUse(state(o)), paid: w.paysPerUse(state(o)) }));

writeFileSync(
  join(here, "../test/fixtures/wizard_vectors.json"),
  `${JSON.stringify({ $comment: "Generated by tool/wizard_vectors.mjs from packages/web/src/wizard.ts: do not edit.", advanced: w.ADVANCED_STEPS, steps, skip, after, presets, presetOf, ways }, null, 1)}\n`,
);
// The ready choices themselves, for the app (careful is every danger the protocol knows).
const dart = Object.entries(w.PRESETS)
  .map(([k, v]) => `  '${k}': [${v.map((x) => `'${x}'`).join(", ")}],`)
  .join("\n");
writeFileSync(
  join(here, "../lib/setup/wizard/wizard_presets.g.dart"),
  `// Generated by tool/wizard_vectors.mjs from packages/web/src/wizard.ts: do not edit.
// ignore_for_file: lines_longer_than_80_chars

/// The dangers only the person approves, for each ready choice (the page's \`PRESETS\`).
const presets = <String, List<String>>{
${dart}
};
`,
);
console.log(`wizard vectors: ${steps.length} step lists`);
