// Writes what the app needs of 3.12.3 from the page and the protocol, never by heart:
//  - lib/settings/agents/agent_sets.g.dart: the ready-made agent sets (AGENT_SETS in
//    packages/protocol/src/agent-sets.ts): id, names, descriptions, the model hint, what each always
//    asks and the connection kinds it wants, it and en;
//  - the page's words of «Start from…», the connections and the calendars (AgentSets.tsx,
//    AgentConnections.tsx, CalendarSettings.tsx: every `t("…")`, and the families `setSpeed_`,
//    `setEffort_`, `calKind_`, `calState_`) into the ARB files, it and en. Each page key `x`
//    becomes the ARB key `sx` + `X` (`setStartFrom` → `sxSetStartFrom`). The ARB is read and
//    written as JSON. Then `flutter gen-l10n`.
//
//   pnpm exec tsc -b packages/protocol && node apps/companion/tool/set_words.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { fillProduct } from "./product.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const web = join(root, "packages/web/src");
const P = await import(pathToFileURL(join(root, "packages/protocol/dist/index.js")).href);

const q = (s) => `r${JSON.stringify(s).replaceAll("$", "\\$")}`;
const words = (w) => `Words(it: ${q(w.it)}, en: ${q(w.en)})`;
const sets = P.AGENT_SETS.map(
  (s) => `  AgentSet(
    id: '${s.id}',
    name: ${words(s.name)},
    description: ${words(s.description)},
    speed: '${s.model.speed}',
    effort: '${s.model.effort}',
    wants: [${s.wants.map((w) => `'${w}'`).join(", ")}],
    asks: [${s.asks.map((a) => words(a.text)).join(", ")}],
  ),`,
).join("\n");
writeFileSync(
  join(here, "../lib/settings/agents/agent_sets.g.dart"),
  `// Generated by tool/set_words.mjs from packages/protocol/src/agent-sets.ts: do not edit.
// The ready-made agent sets (3.12.3), as the page and the server have them.
// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes, unnecessary_string_escapes
import '../../l10n/set_types.dart';

const agentSets = <AgentSet>[
${sets}
];
`,
);

const src = readFileSync(join(web, "i18n.ts"), "utf8");
const itAt = src.indexOf("\nconst it:");
const parts = { en: src.slice(0, itAt), it: src.slice(itAt) };
const lit = String.raw`(?:"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')`;
const entry = new RegExp(
  String.raw`^ {2}([A-Za-z0-9_]+):\s*\n?\s*(${lit}(?:\s*\+\s*\n?\s*${lit})*),?$`,
  "gm",
);
const page = { it: {}, en: {} };
for (const [lang, text] of Object.entries(parts))
  for (const m of text.matchAll(entry)) page[lang][m[1]] = fillProduct(new Function(`return ${m[2]};`)());

const skip = new Set(["cancel", "save", "settings", "extChecking", "extWorks", "extNeedsLogin", "extBroken", "asstNoServices", "asstAddService", "remove"]);
const wanted = new Set();
for (const f of ["AgentSets.tsx", "AgentConnections.tsx", "CalendarSettings.tsx"])
  for (const m of readFileSync(join(web, "components", f), "utf8").matchAll(/\bt\(\s*"([A-Za-z0-9_]+)"/g))
    if (!skip.has(m[1])) wanted.add(m[1]);
for (const k of Object.keys(page.en))
  if (["setSpeed_", "setEffort_", "calKind_", "calState_"].some((p) => k.startsWith(p))) wanted.add(k);
for (const k of ["connMailboxes", "connChats", "connCalendars", "connServices", "agentTab_connections", "setUsed", "calTitle", "connTitle", "connHelp", "connCount"]) wanted.add(k);
for (const lang of ["it", "en"])
  for (const k of wanted) if (!(k in page[lang])) throw new Error(`no ${lang} word ${k}`);

const arbKey = (k) => `sx${k[0].toUpperCase()}${k.slice(1)}`;
const holes = (s) => [...new Set([...s.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((m) => m[1]))].sort();
for (const lang of ["en", "it"]) {
  const file = join(here, `../lib/l10n/app_${lang}.arb`);
  const arb = JSON.parse(readFileSync(file, "utf8"));
  for (const k of [...wanted].sort()) {
    const value = page[lang][k];
    const names = holes(value);
    const other = holes(page[lang === "en" ? "it" : "en"][k]);
    if (names.join() !== other.join()) throw new Error(`${k}: it and en have different words`);
    arb[arbKey(k)] = value;
    if (lang === "en" && names.length)
      arb[`@${arbKey(k)}`] = {
        placeholders: Object.fromEntries(names.map((n) => [n, { type: "String" }])),
      };
  }
  writeFileSync(file, `${JSON.stringify(arb, null, 2)}\n`);
}
console.log(`${wanted.size} words, ${P.AGENT_SETS.length} sets`);
