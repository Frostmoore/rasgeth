// Writes lib/settings/general_words.g.dart and test/fixtures/word_diff_vectors.json (G42.4): what
// Settings › General shows as the page does, taken from the page and the protocol, never by heart:
// the agents' languages (`AGENT_LANGUAGES`), the web search services (`SEARCH_PROVIDERS` with the
// page's `searchCard_<id>` and `searchHow_<id>` words), who writes down voice messages in the cloud
// (`VOICE_PROVIDERS` with speech to text), «What's new» (`ITEMS` and `NEWS_VERSION` of
// WhatsNew.tsx with their `news…` words, it and en), and the refiner's word diff on a few texts
// (`wordDiff`/`diffCounts` of packages/web/src/word-diff.ts) for the Dart port's test.
//
//   node --experimental-strip-types apps/companion/tool/general_words.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fillProduct } from "./product.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const { AGENT_LANGUAGES } = await import(join(repo, "packages/protocol/src/languages.ts"));
const { SEARCH_PROVIDERS } = await import(join(repo, "packages/protocol/src/search.ts"));
const { VOICE_PROVIDERS } = await import(join(repo, "packages/protocol/src/voice.ts"));
const { wordDiff, diffCounts } = await import(join(repo, "packages/web/src/word-diff.ts"));

// The page's words, it and en (a value may be split over lines with «+»).
const src = readFileSync(join(repo, "packages/web/src/i18n.ts"), "utf8");
const itAt = src.indexOf("\nconst it:");
const parts = { en: src.slice(0, itAt), it: src.slice(itAt) };
// A string literal, double or single quoted, maybe several joined with «+».
const lit = String.raw`(?:"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')`;
const entry = new RegExp(String.raw`^ {2}([A-Za-z0-9_]+):\s*\n?\s*(${lit}(?:\s*\+\s*\n?\s*${lit})*),?$`, "gm");
const words = { it: {}, en: {} };
for (const [lang, text] of Object.entries(parts))
  // The page's own source: its literals are read as JavaScript reads them.
  for (const m of text.matchAll(entry)) words[lang][m[1]] = fillProduct(new Function(`return ${m[2]};`)());

const news = readFileSync(join(repo, "packages/web/src/components/WhatsNew.tsx"), "utf8");
const newsVersion = news.match(/NEWS_VERSION = "([^"]+)"/)[1];
const items = [
  ...news.matchAll(/\{ version: "([^"]+)", title: "([A-Za-z0-9_]+)", text: "([A-Za-z0-9_]+)" \}/g),
].map((m) => ({ version: m[1], title: m[2], text: m[3] }));

const wanted = new Set();
for (const i of items) wanted.add(i.title).add(i.text);
for (const p of SEARCH_PROVIDERS) wanted.add(`searchCard_${p.id}`).add(`searchHow_${p.id}`);
for (const lang of ["it", "en"])
  for (const k of wanted) if (!(k in words[lang])) throw new Error(`no ${lang} word ${k}`);

const q = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n").replace(/\$/g, "\\$")}'`;
const opt = (s) => (s === undefined ? "null" : q(s));
const dartWords = (lang) =>
  [...wanted]
    .sort()
    .map((k) => `    ${q(k)}: ${q(words[lang][k])},`)
    .join("\n");

const languages = AGENT_LANGUAGES.map(
  (l) => `  AgentLanguageRow(${q(l.code)}, ${q(l.native)}, ${q(l.en)}, ${q(l.it)}, common: ${!!l.common}),`,
).join("\n");
const search = SEARCH_PROVIDERS.map(
  (p) =>
    `  SearchProviderRow(${q(p.id)}, ${q(p.name)}, needsUrl: ${p.needs === "url"}, keyUrl: ${q(p.keyUrl)}, keyExample: ${opt(p.keyExample)}),`,
).join("\n");
const stt = VOICE_PROVIDERS.filter((p) => p.stt?.length)
  .map((p) => {
    const models = p.stt
      .map(
        (m) =>
          `      SttModelRow(${q(m.id)}, ${q(m.label)}, usd: ${m.price ? m.price.usd : "null"}, per: ${opt(m.price?.per)}, closes: ${opt(m.closes)}),`,
      )
      .join("\n");
    return `  SttProviderRow(${q(p.id)}, ${q(p.name)}, keyUrl: ${q(p.keyUrl)}, keyExample: ${q(p.keyExample)}, models: [\n${models}\n  ]),`;
  })
  .join("\n");
const newsRows = items
  .map((i) => `  NewsRow(${q(i.version)}, ${q(i.title)}, ${q(i.text)}),`)
  .join("\n");

writeFileSync(
  join(here, "../lib/settings/general_words.g.dart"),
  `// Generated by tool/general_words.mjs from the protocol (languages.ts, search.ts, voice.ts) and the
// page (i18n.ts, WhatsNew.tsx): do not edit.
// ignore_for_file: lines_longer_than_80_chars
import 'general_types.dart';

/// The release whose news the page shows last (WhatsNew.tsx's NEWS_VERSION).
const newsVersion = ${q(newsVersion)};

/// Every item, in the page's order (newest release first).
const newsRows = <NewsRow>[
${newsRows}
];

const agentLanguages = <AgentLanguageRow>[
${languages}
];

const searchProviders = <SearchProviderRow>[
${search}
];

const sttProviders = <SttProviderRow>[
${stt}
];

/// The page's words for the news and the search services.
const generalWords = <String, Map<String, String>>{
  'it': {
${dartWords("it")}
  },
  'en': {
${dartWords("en")}
  },
};
`,
);

const samples = [
  ["You are kind.", "You are kind and brief."],
  ["Answer in Italian.\nNever push.", "Answer in English.\nNever push without asking."],
  ["", "Something new"],
  ["Same text", "Same text"],
  ["Use {god} for help, then «stop».", "Ask {god} first; then stop."],
  ["Città è bella", "Città non è bella"],
];
writeFileSync(
  join(here, "../test/fixtures/word_diff_vectors.json"),
  `${JSON.stringify(
    samples.map(([before, after]) => {
      const p = wordDiff(before, after);
      return { before, after, parts: p, counts: diffCounts(p) };
    }),
    null,
    2,
  )}\n`,
);
console.log(
  `${AGENT_LANGUAGES.length} languages, ${SEARCH_PROVIDERS.length} search, ${items.length} news, ${samples.length} diffs`,
);
