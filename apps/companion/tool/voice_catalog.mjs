// Writes lib/voice/voice_catalog.g.dart: who can read the answers aloud through the server
// (`VOICE_PROVIDERS` in packages/protocol/src/voice.ts, its text-to-speech models and voices),
// so the app offers the same choices as the page's Settings › Voice.
//   pnpm --filter @redgiant/protocol build && node apps/companion/tool/voice_catalog.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { VOICE_PROVIDERS, voicesForModel } from "../../../packages/protocol/dist/voice.js";

const here = dirname(fileURLToPath(import.meta.url));
const q = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
const rows = VOICE_PROVIDERS.filter((p) => p.tts?.length).map((p) => {
  const models = p.tts.map((m) => {
    const voices = voicesForModel(p, m.id)
      .map((v) => `VoiceOption(${q(v.id)}, ${q(v.label)})`)
      .join(", ");
    return `      SpeechModel(${q(m.id)}, ${q(m.label)}, [${voices}]),`;
  });
  return `  SpeechProvider(${q(p.id)}, ${q(p.name)}, [\n${models.join("\n")}\n  ]),`;
});
writeFileSync(
  join(here, "../lib/voice/voice_catalog.g.dart"),
  `// Generated by tool/voice_catalog.mjs from packages/protocol/src/voice.ts: do not edit.
// The providers that read answers aloud through the server, newest model first.
// ignore_for_file: lines_longer_than_80_chars
import 'voice_types.dart';

const speechProviders = <SpeechProvider>[
${rows.join("\n")}
];
`,
);
