// Writes lib/l10n/rule_words.g.dart: the protocol's words for the permission dangers
// (`dangerWords`, packages/protocol/src/dangers.ts) and for the truly dangerous requests
// (`criticalWords`, critical.ts), it and en, so the app's Safety and Requests pages say them as the
// page does (G42.4). The two files are loaded as they are, with zod stubbed (only schemas use it).
//
//   node --experimental-strip-types apps/companion/tool/rule_words.mjs
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { fillProduct } from "./product.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "../../../packages/protocol/src");
const tmp = join(here, "../build/rule-words");
mkdirSync(tmp, { recursive: true });
// brand.ts too: the words may name the product (`PRODUCT_NAME`, plan 3.9.0).
const fix = (s) =>
  s
    .replace(/from "zod"/g, 'from "./zod.ts"')
    .replace(/"\.\/(critical|brand)\.js"/g, '"./$1.ts"');
for (const f of ["critical.ts", "dangers.ts", "brand.ts"])
  writeFileSync(join(tmp, f), fix(readFileSync(join(src, f), "utf8")));
writeFileSync(
  join(tmp, "zod.ts"),
  "const f: any = new Proxy(function () {}, { get: () => f, apply: () => f });\nexport const z = f;\n",
);
const critical = await import(pathToFileURL(join(tmp, "critical.ts")).href);
const dangers = await import(pathToFileURL(join(tmp, "dangers.ts")).href);
rmSync(tmp, { recursive: true, force: true });

const fixed = ["outgoing-mail", "agent-model"];
const ids = [...dangers.DANGER_IDS, ...fixed];
const q = (s) => `r${JSON.stringify(fillProduct(s))}`;
const lang = (l) => {
  const d = ids
    .map((id) => {
      const w = dangers.dangerWords(l, id);
      return `      '${id}': (name: ${q(w.name)}, hint: ${q(w.hint)}),`;
    })
    .join("\n");
  const c = critical.CRITICAL_IDS.map((id) => {
    const w = critical.criticalWords(l, id);
    return `      '${id}': (name: ${q(w.name)}, hint: ${q(w.hint)}, examples: [${w.examples.map(q).join(", ")}]),`;
  }).join("\n");
  return `  '${l}': (\n    dangers: {\n${d}\n    },\n    critical: {\n${c}\n    },\n  ),`;
};
const file = join(here, "../lib/l10n/rule_words.g.dart");
writeFileSync(
  file,
  `// Generated by tool/rule_words.mjs from packages/protocol/src/dangers.ts and critical.ts: do not edit.
// The permission dangers and the truly dangerous requests, as the page says them.
// ignore_for_file: lines_longer_than_80_chars, prefer_single_quotes, unnecessary_string_escapes
typedef DangerWords = ({String name, String hint});
typedef CriticalWords = ({String name, String hint, List<String> examples});

/// The ids of the policy's dangers on the Safety page (\`DANGER_IDS\`), in order.
const dangerIds = <String>[${dangers.DANGER_IDS.map((x) => `'${x}'`).join(", ")}];

/// The truly dangerous requests (\`CRITICAL_IDS\`), in order.
const criticalIds = <String>[${critical.CRITICAL_IDS.map((x) => `'${x}'`).join(", ")}];

const ruleWords = <String, ({Map<String, DangerWords> dangers, Map<String, CriticalWords> critical})>{
${lang("it")}
${lang("en")}
};
`,
);
console.log(`${ids.length} dangers, ${critical.CRITICAL_IDS.length} critical -> ${file}`);
