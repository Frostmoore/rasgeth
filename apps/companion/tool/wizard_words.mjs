// Writes lib/setup/wizard/wizard_words.g.dart (G42.17): the setup wizard's words as the page
// says them (packages/web/src/i18n.ts: Setup.tsx's `wz…`, `fb…`, ImportFrom's `imp…`, ExternalAgents'
// `acp…`, Platform's `chg…`/`history…`/`tech…`), it
// and en, never by heart. Words only the app says are in the app's .arb files with the prefix `g7`.
//
//   node apps/companion/tool/wizard_words.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fillProduct } from "./product.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const src = readFileSync(join(repo, "packages/web/src/i18n.ts"), "utf8");
const itAt = src.indexOf("\nconst it:");
const parts = { en: src.slice(0, itAt), it: src.slice(itAt) };
const lit = String.raw`(?:"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')`;
const entry = new RegExp(String.raw`^ {2}([A-Za-z0-9_]+):\s*\n?\s*(${lit}(?:\s*\+\s*\n?\s*${lit})*),?$`, "gm");
const words = { it: {}, en: {} };
for (const [lang, text] of Object.entries(parts))
  for (const m of text.matchAll(entry)) words[lang][m[1]] = fillProduct(new Function(`return ${m[2]};`)());

const wanted = ["wzWelcome", "wzRole", "wzAccount", "wzMachine", "wzMode", "wzBrain", "wzLocal", "wzNames", "wzAssign", "wzImport", "wzTelegram", "wzStorage", "wzCode", "wzRemote", "wzSafety", "wzDone", "wzHello", "wzHelloLead", "wzModeQ", "wzModeLead", "wzLook", "wzLookQ", "wzLookLead", "wzLookSimple", "wzLookSimpleText", "wzLookFull", "wzLookFullText", "wzLookName", "wzLookNameHint", "uiSimple", "uiFull", "wzModeStdText", "wzModeAdvText", "modeStandard", "modeAdvanced", "wzBrainQ", "wzBrainLead", "wzLocalQ", "wzLocalLead", "wzNamesQ", "wzNamesLead", "wzGodRole", "wzDemiRole", "wzDoneQ", "wzDoneLead", "wzWhatNow", "wzRunAgainSettings", "fbRoleQ", "fbRoleLead", "fbAccountQ", "fbAccountLead", "fbMachineQ", "fbMachineLead", "fbStorageQ", "fbStorageLead", "wzRemoteQ", "fbRemoteLead", "wzCodeQ", "wzCodeLead", "wzSafetyLead", "impQ", "impLead", "wzStart", "wzNext", "wzFinish", "wzBack", "wzSkip", "wzSaving", "wzNofN", "wzAllSteps", "wzAllStepsLead", "wzHere", "wzSeen", "wzChange", "wzSaved", "wzPreset_careful", "wzPreset_balanced", "wzPreset_free", "fbPasswordNeeded", "fbPasswordWeak", "fbPasswordDiffer", "wzLangIt", "wzLangEn", "wzCpu", "wzMemory", "wzGpu", "wzNoGpu", "wzNextProject", "wzNextAsk", "wzNextAskText", "wzNextPhone", "wzNextPhoneText"];
// Import from other agents (ImportFrom.tsx): every `imp…` word of the page.
// External agents (ExternalAgents.tsx: `acp…`) and the history of changes (Platform.tsx and
// changes.ts: `chg…`, `history…`, `tech…`), every word of theirs.
for (const k of Object.keys(words.en))
  if (/^(imp|acp|chg|history|tech|agentMode_)[A-Za-z_]/.test(k) && k in words.it) wanted.push(k);
wanted.push("sbPlatformQ", "platformView", "noChanges", "releases", "before", "after", "undo", "discard", "wzNotNow", "you", "supervisorName", "extEverywhere", "extOnlyProject", "kitOn", "kitOff", "kitAuto");
{
  const unique = [...new Set(wanted)];
  wanted.length = 0;
  wanted.push(...unique);
}
for (const lang of ["it", "en"])
  for (const k of wanted) if (!(k in words[lang])) throw new Error(`no ${lang} word ${k}`);

const q = (s) =>
  `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n").replace(/\$/g, "\\$")}'`;
const dart = (lang) => wanted.map((k) => `    ${q(k)}: ${q(words[lang][k])},`).join("\n");
writeFileSync(
  join(here, "../lib/setup/wizard/wizard_words.g.dart"),
  `// Generated by tool/wizard_words.mjs from the page (i18n.ts): do not edit.
// ignore_for_file: lines_longer_than_80_chars

/// The setup wizard's words as the page says them, it and en ({name} filled by [wzWord]).
const wizardWords = <String, Map<String, String>>{
  'it': {
${dart("it")}
  },
  'en': {
${dart("en")}
  },
};
`,
);
console.log(`wizard words: ${wanted.length}`);
