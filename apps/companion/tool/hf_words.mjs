// Writes lib/voice/hands_free/hf_words.g.dart (G42.16): the words of hands-free voice as the page
// says them (packages/web/src/i18n.ts: the indicator's `voice…` and Settings › Voice's `vc…`), it
// and en, never by heart. Words only the app says (the foreground service, the wake word on this
// device, the limits of the app) are in the app's .arb files with the prefix `hf`.
//
//   node apps/companion/tool/hf_words.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fillProduct } from "./product.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const src = readFileSync(join(repo, "packages/web/src/i18n.ts"), "utf8");
const itAt = src.indexOf("\nconst it:");
const parts = { en: src.slice(0, itAt), it: src.slice(itAt) };
const lit = String.raw`(?:"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')`;
const entry = new RegExp(String.raw`^ {2}([A-Za-z0-9_]+):\s*\n?\s*(${lit}(?:\s*\+\s*\n?\s*${lit})*),?$`, "gm");
const words = { it: {}, en: {} };
for (const [lang, text] of Object.entries(parts))
  for (const m of text.matchAll(entry)) words[lang][m[1]] = fillProduct(new Function(`return ${m[2]};`)());

const wanted = [
  "voiceTitle",
  "voiceListening",
  "voiceFollowup",
  "voiceTranscribing",
  "voiceThinking",
  "voiceSpeaking",
  "voiceWaiting",
  "voiceTapToTalk",
  "voiceMicDenied",
  "voiceStop",
  "voiceTalk",
  "voiceSwitchOff",
  "voiceSettings",
  "voiceTooLong",
  "voiceNoConversation",
  "voiceRestOnScreen",
  "voiceModelAbout",
  "voiceModelGet",
  "voiceModelReady",
  "voiceModelError",
  "vcQ",
  "vcLead",
  "vcNoTranscription",
  "vcChooseTranscription",
  "vcEnabled",
  "vcEnabledHelp",
  "vcWakeTitle",
  "vcWake",
  "vcWakeWord",
  "vcWakeUse",
  "vcWakeExamples",
  "vcWakeWordHelp",
  "vcWakeSaved",
  "vcWakeNeedsModel",
  "vcWakeUnknown",
  "vcWakeProblem_empty",
  "vcWakeProblem_tooLong",
  "vcWakeProblem_stopWord",
  "vcWakeProblem_short",
  "vcSensitivity",
  "vcSens1",
  "vcSens2",
  "vcSens3",
  "vcSens4",
  "vcSens5",
  "vcSensitivityHelp",
  "vcLangTitle",
  "vcLang",
  "vcLangIt",
  "vcLangEn",
  "vcSttTitle",
  "vcSttLead",
  "vcSttTry",
  "vcSttTrySpeak",
  "vcSttHeard",
  "vcSttHeardNothing",
  "vcReaderTitle",
  "vcReaderLead",
  "vcVolume",
  "vcTalkTitle",
  "vcFollowup",
  "vcFollowupOff",
  "vcSeconds",
  "vcFollowupHelp",
  "vcBargeIn",
  "vcBargeInHelp",
  "vcTarget",
  "vcTargetOpen",
  "vcTargetFixed",
  "vcLimitsTitle",
  "vcLimitSpeakers",
];
for (const lang of ["it", "en"])
  for (const k of wanted) if (!(k in words[lang])) throw new Error(`no ${lang} word ${k}`);

const q = (s) =>
  `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n").replace(/\$/g, "\\$")}'`;
const dart = (lang) => wanted.map((k) => `    ${q(k)}: ${q(words[lang][k])},`).join("\n");
writeFileSync(
  join(here, "../lib/voice/hands_free/hf_words.g.dart"),
  `// Generated by tool/hf_words.mjs from the page (i18n.ts): do not edit.
// ignore_for_file: lines_longer_than_80_chars

/// Hands-free voice's words as the page says them, it and en ({name} filled by [hfWord]).
const hfWords = <String, Map<String, String>>{
  'it': {
${dart("it")}
  },
  'en': {
${dart("en")}
  },
};
`,
);
console.log(`hands-free words: ${wanted.length}`);
