// Writes lib/settings/extensions/ext_catalog.g.dart (G42.11): the page's catalog of services
// (MCP_CATALOG), the providers that make pictures, video and sound (MEDIA_PROVIDERS, MEDIA_KINDS)
// and the keychain's name rule (VAULT_NAME_RE), from @redgiant/protocol itself, so the app shows
// and sends the very same; and test/fixtures/ext_vectors.json: what the protocol's `catalogConfig`
// makes of each entry with the person's input, for the Dart port (lib/settings/extensions/
// ext_catalog.dart) to match.
//
//   pnpm exec tsc -b packages/protocol && node apps/companion/tool/ext_catalog.mjs
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const lib = resolve(process.argv[2] ?? join(here, "../../../packages/protocol/dist/index.js"));
const { MCP_CATALOG, MEDIA_PROVIDERS, MEDIA_KINDS, VAULT_NAME_RE, catalogConfig } = await import(
  pathToFileURL(lib).href
);

const data = JSON.stringify({
  catalog: MCP_CATALOG,
  media: { kinds: MEDIA_KINDS, providers: MEDIA_PROVIDERS },
  vaultName: VAULT_NAME_RE.source,
});
if (data.includes("'''")) throw new Error("the catalog has three quotes in a row");
writeFileSync(
  join(here, "../lib/settings/extensions/ext_catalog.g.dart"),
  `// Generated by tool/ext_catalog.mjs from @redgiant/protocol (MCP_CATALOG, MEDIA_PROVIDERS,
// MEDIA_KINDS, VAULT_NAME_RE): do not edit.
// ignore_for_file: lines_longer_than_80_chars
const extCatalogJson = r'''${data}''';
`,
);

// The person's input for each kind of sign-in, and what the protocol makes of it.
const input = (e) => ({
  key: "  sk-test-1234  ",
  url: e.userUrl ? "https://home.example.org:8123/" : "",
  fields: Object.fromEntries(
    e.auth.type === "fields" ? e.auth.fields.map((f) => [f.env, ` ${f.env.toLowerCase()} `]) : [],
  ),
  app: { clientId: " client-1 ", clientSecret: e.auth.type === "app" && e.auth.secret ? "s3" : "" },
});
const vectors = [];
for (const e of MCP_CATALOG) {
  const given = input(e);
  let out;
  try {
    out = { ok: catalogConfig(e, given) };
  } catch (err) {
    out = { error: String(err.message) };
  }
  vectors.push({ id: e.id, input: given, ...out });
  // And with nothing typed: what is refused.
  try {
    vectors.push({ id: e.id, input: {}, ok: catalogConfig(e, {}) });
  } catch (err) {
    vectors.push({ id: e.id, input: {}, error: String(err.message) });
  }
}
writeFileSync(
  join(here, "../test/fixtures/ext_vectors.json"),
  `${JSON.stringify({ vectors }, null, 2)}\n`,
);
console.log(`${MCP_CATALOG.length} services, ${MEDIA_PROVIDERS.length} media providers, ${vectors.length} vectors`);
