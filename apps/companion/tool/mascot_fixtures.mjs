// Writes test/fixtures/mascots.json: specs and SVGs made by @redgiant/mascot (the library the
// server uses), so the app's tests draw exactly what the server sends; and
// lib/mascot/motion_table.g.dart: the library's motion table, the same one the page's CSS comes
// from (packages/mascot/test/motion.test.ts fails when it is out of date).
//
//   pnpm build && node apps/companion/tool/mascot_fixtures.mjs [path/to/mascot/dist/index.js]
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const lib = resolve(process.argv[2] ?? join(here, "../../../packages/mascot/dist/index.js"));
const {
  mascotSpec,
  mascotSvg,
  subagentSignSvg,
  MASCOT_STATES,
  MASCOT_MOTION,
  rareStarts,
  rhythmOf,
} = await import(pathToFileURL(lib).href);

const parent = mascotSpec("Coder Web", "agent");
// Sub-agents have no mascot (2026-11-19): their sign is in subagent_signs.json below.
const cases = [
  ["God", "god"],
  ["Demi", "demigod"],
  ["Capo cantiere", "orchestrator"],
  ["Coder Web", "agent"],
  ["Ricercatore", "agent"],
  ["Assistente mail", "assistant"],
  ["Revisore", "inspector"],
];

const out = cases.map(([seed, kind, p]) => {
  const spec = mascotSpec(seed, kind, p);
  const svg = {};
  for (const theme of ["light", "dark"]) {
    svg[theme] = {};
    for (const state of MASCOT_STATES)
      svg[theme][state] = mascotSvg(spec, { state, theme, size: 128, idPrefix: "m" });
  }
  const tiny = mascotSvg(spec, { state: "idle", theme: "light", size: 20, idPrefix: "m" });
  const compact = mascotSvg(spec, { state: "idle", theme: "light", size: 32, idPrefix: "m" });
  return { seed, kind, spec, svg, tiny, compact };
});

const file = join(here, "../test/fixtures/mascots.json");
writeFileSync(file, `${JSON.stringify(out, null, 1)}\n`);
console.log(`${out.length} mascots -> ${file}`);

// A sub-agent's sign (board choice A): in its parent's colour and grey without one, every state
// and theme, for the app's painter (subagent_sign.dart) to match.
const signs = [
  ["Coder Web", parent],
  ["", undefined],
].map(([parentSeed, p]) => {
  const svg = {};
  for (const theme of ["light", "dark"]) {
    svg[theme] = {};
    for (const state of MASCOT_STATES)
      svg[theme][state] = subagentSignSvg(p, { state, theme, size: 96 });
  }
  return { parent: parentSeed, ...(p && { spec: p }), svg };
});
const sfile = join(here, "../test/fixtures/subagent_signs.json");
writeFileSync(sfile, `${JSON.stringify(signs, null, 1)}\n`);
console.log(`${signs.length} signs -> ${sfile}`);

const table = join(here, "../lib/mascot/motion_table.g.dart");
writeFileSync(
  table,
  `// Generated by tool/mascot_fixtures.mjs from @redgiant/mascot (MASCOT_MOTION): do not edit.
// The mascots' motion, the same table the page's CSS is made from.
// ignore_for_file: lines_longer_than_80_chars
const mascotMotionJson = r'''${JSON.stringify(MASCOT_MOTION)}''';
`,
);
console.log(`motion table -> ${table}`);

// The rhythm and the rare events' times, so the app's own port (motion.dart) is checked against
// the library's numbers.
const seeds = ["God", "Chat", "Coder Web", "Ricercatore", "Revisore", "Assistente mail", "Àgata"];
const vectors = seeds.map((seed) => {
  const k = rhythmOf(seed);
  const rare = {};
  for (const [state, tracks] of Object.entries(MASCOT_MOTION.states))
    for (const t of tracks)
      if (t.rare && rare[`${state}:${t.rare.ev}`] === undefined)
        rare[`${state}:${t.rare.ev}`] = rareStarts(t, k, 0, 200);
  return { seed, k, rare };
});
const vfile = join(here, "../test/fixtures/motion_vectors.json");
writeFileSync(vfile, `${JSON.stringify(vectors)}\n`);
console.log(`motion vectors -> ${vfile}`);
